import { Ionicons } from '@expo/vector-icons'
import { useMemo, useState } from 'react'
import { Pressable, StyleSheet, View } from 'react-native'
import { buildLessonSession } from '../../core/exercises'
import { gradeBank, gradeSay } from '../../core/grading'
import type { BankExercise, GradeResult, SayExercise } from '../../core/types'
import { useT } from '../../i18n'
import { canSpeak } from '../../lib/speech'
import { useCourse, useTarget } from '../../state/course'
import { useApp } from '../../state/store'
import { colors, radius, space } from '../../theme/tokens'
import { Button } from '../../ui/Button'
import { Txt } from '../../ui/Txt'
import { BankView, SayView, isDraftReady, type Draft } from '../lesson/views'

type Kind = 'say' | 'bank'

/**
 * A real exercise on the landing page, so the page shows the product instead
 * of describing it: the speaking finale and a sentence to build, generated by
 * the same code and graded by the same rules as inside a lesson. Nothing is
 * saved; the visitor is still a visitor.
 */
export function LandingDemo({ onStart }: { onStart: () => void }) {
  const t = useT()
  const lang = useApp((s) => s.user.profile.baseLang)
  const target = useTarget()
  const course = useCourse()
  const [micAvailable] = useState(() => canSpeak())

  // the first lesson, in the visitor's language: a handful of "say" and "build the sentence" rounds
  const pool = useMemo(() => {
    const unit = course.units[0]
    if (!unit) return { say: [] as SayExercise[], bank: [] as BankExercise[], lexicon: new Set<string>() }
    const built = buildLessonSession(unit, 0, { baseLang: lang, target, seed: 7, canListen: false, canSpeak: false })
    return {
      say: built.exercises.filter((e): e is SayExercise => e.kind === 'say'),
      bank: built.exercises.filter((e): e is BankExercise => e.kind === 'bank' && e.direction === 'native-en'),
      lexicon: new Set(built.lexicon),
    }
  }, [lang, target, course])

  const [kind, setKind] = useState<Kind>('say')
  const [index, setIndex] = useState(0)
  const [draft, setDraft] = useState<Draft | null>(null)
  const [result, setResult] = useState<GradeResult | null>(null)

  const list = kind === 'say' ? pool.say : pool.bank
  const exercise = list[index % Math.max(1, list.length)]
  if (!exercise) return null

  const switchTo = (next: Kind) => {
    setKind(next)
    setIndex(0)
    setDraft(null)
    setResult(null)
  }
  const another = () => {
    setIndex((i) => i + 1)
    setDraft(null)
    setResult(null)
  }
  const check = () => {
    if (!draft) return
    if (exercise.kind === 'say' && draft.kind === 'text') setResult(gradeSay(exercise, draft.value, draft.spoken === true, pool.lexicon))
    if (exercise.kind === 'bank' && draft.kind === 'tiles') setResult(gradeBank(exercise, draft.value.map((i) => exercise.tokens[i] ?? ''), lang))
  }

  const common = { draft, setDraft, locked: result !== null, result, guide: 'everest' as const, sound: false, haptics: false }

  return (
    <View style={styles.card} testID="landing-demo">
      <View style={styles.switch}>
        {(['say', 'bank'] as const).map((k) => (
          <Pressable key={k} accessibilityRole="tab" accessibilityState={{ selected: kind === k }} onPress={() => switchTo(k)} style={[styles.switchItem, kind === k ? styles.switchOn : null]} testID={`demo-${k}`}>
            <Ionicons name={k === 'say' ? 'mic' : 'construct'} size={16} color={kind === k ? colors.primaryEdge : colors.textSoft} />
            <Txt variant="label" color={kind === k ? colors.primaryEdge : colors.textSoft}>
              {t(k === 'say' ? 'landing.demo.say' : 'landing.demo.bank')}
            </Txt>
          </Pressable>
        ))}
      </View>

      <View key={`${exercise.id}-${index}`}>
        {exercise.kind === 'say' ? <SayView exercise={exercise} {...common} canUseMic={micAvailable} /> : <BankView exercise={exercise} {...common} />}
      </View>

      {result ? (
        <View style={[styles.feedback, { backgroundColor: result.correct ? colors.successSoft : colors.dangerSoft }]} testID="demo-feedback">
          <View style={styles.feedbackRow}>
            <Ionicons name={result.correct ? 'checkmark-circle' : 'close-circle'} size={26} color={result.correct ? colors.successText : colors.dangerText} />
            <Txt variant="heading" color={result.correct ? colors.successText : colors.dangerText}>
              {result.correct ? (result.typo ? t('lesson.typo') : t('lesson.correct')) : t('lesson.wrong')}
            </Txt>
          </View>
          {result.missed && result.missed.length > 0 ? (
            <Txt color={result.correct ? colors.successText : colors.dangerText}>
              {result.expected.split(/\s+/).map((word, i) => (
                <Txt key={i} color={result.correct ? colors.successText : colors.dangerText} style={result.missed?.includes(word) ? styles.missed : null}>
                  {i > 0 ? ' ' : ''}
                  {word}
                </Txt>
              ))}
            </Txt>
          ) : !result.correct || result.typo ? (
            <Txt color={result.correct ? colors.successText : colors.dangerText}>{result.expected}</Txt>
          ) : null}
        </View>
      ) : null}

      <View style={styles.actions}>
        {result ? (
          <>
            <Button label={t('landing.demo.next')} variant="secondary" onPress={another} testID="demo-next" />
            <Button label={t('landing.cta')} variant="success" onPress={onStart} />
          </>
        ) : (
          <Button label={t('lesson.check')} variant="success" disabled={!isDraftReady(draft)} onPress={check} testID="demo-check" />
        )}
      </View>
    </View>
  )
}

const styles = StyleSheet.create({
  card: { width: '100%', maxWidth: 520, alignSelf: 'center', backgroundColor: colors.white, borderWidth: 2, borderColor: colors.border, borderRadius: radius.xl, padding: space.lg, gap: space.md },
  switch: { flexDirection: 'row', padding: 4, borderRadius: radius.lg, backgroundColor: colors.surface, borderWidth: 2, borderColor: colors.border },
  switchItem: { flex: 1, flexDirection: 'row', alignItems: 'center', justifyContent: 'center', gap: 6, paddingVertical: 8, borderRadius: radius.md },
  switchOn: { backgroundColor: colors.white, borderWidth: 2, borderColor: colors.primarySoft },
  feedback: { borderRadius: radius.lg, padding: space.md, gap: 6 },
  feedbackRow: { flexDirection: 'row', alignItems: 'center', gap: space.sm },
  missed: { fontWeight: '800', textDecorationLine: 'underline' },
  actions: { gap: space.sm },
})
